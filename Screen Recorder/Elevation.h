// =============================================================
//  Elevation.h - "التشغيل كمسؤول" (اختياري، من الإعدادات ← عام)
//
//  ليش؟ الألعاب اللي شغّالة كمسؤول (كتير منها فيها مضاد غش) ويندوز بيمنع
//  البرامج العادية تشوف الأزرار وهي قدامك، فالاختصارات ما بتشتغل جوّاها.
//  إذا البرنامج نفسه شغّال كمسؤول، بيصير بنفس مستواها وكلشي بيشتغل.
//
//  كيف؟
//   - عند الفتح: إذا الإعداد مفعّل والبرنامج مش مسؤول، بيعيد فتح حاله بـ "runas"
//     (ويندوز بيسأل موافقة) والنسخة الأولى بتطلع. النسخة الجديدة بتاخد الدور
//     بـ --elevated-restart (بتستنى الأولى تسكّر بدل ما تعتبر حالها نسخة تانية)
//   - التشغيل مع ويندوز: البرامج اللي بدها مسؤول ما بتشتغل من مفتاح Run بالريجستري،
//     فمنستعمل "جدولة المهام" (Task Scheduler) بأعلى صلاحية: بتفتح مع الدخول بلا ما تسأل
//   - إذا رفضت الموافقة: البرنامج بيكمّل عادي بصلاحية عادية
// =============================================================
#pragma once
#ifndef NOMINMAX
#define NOMINMAX
#endif
#include <windows.h>
#include <string>

bool IsElevated();                                   // البرنامج شغّال كمسؤول هلق؟
bool RelaunchElevated(const std::wstring& args);     // false = رفضت الموافقة أو فشل

// مهمة "التشغيل مع ويندوز" بجدولة المهام (بأعلى صلاحية) — بدها البرنامج يكون مسؤول لإنشائها/حذفها
bool StartupTaskExists();
bool CreateStartupTask(const std::wstring& exe, const std::wstring& args);
bool DeleteStartupTask();

// رسائل لازم توصل للنسخة "المسؤول" من البرامج العادية (متل explorer: أيقونة الساعة)
// ويندوز بيمنعها افتراضيًا (UIPI)، فمنسمح فيها بالاسم
void AllowMessageFromLowerPrivilege(HWND hwnd, UINT msg);
